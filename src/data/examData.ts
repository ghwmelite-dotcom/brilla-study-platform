export function getExamTypeBySlug(slug: string): ExamType | undefined {
  return examTypes.find((e) => e.slug === slug);
}

export function getSubjectsByExamType(examTypeSlug: string): Subject[] {
  const examType = examTypes.find((e) => e.slug === examTypeSlug);
  if (!examType) return [];
  return subjects.filter((s) => s.examTypeId === examType.id);
}

export function getCategoriesByExamType(examTypeSlug: string): SubjectCategory[] {
  const examType = examTypes.find((e) => e.slug === examTypeSlug);
  if (!examType) return [];
  return subjectCategories.filter((c) => c.examTypeId === examType.id);
}

export function getPaperTypesByExamType(examTypeSlug: string): PaperType[] {
  const examType = examTypes.find((e) => e.slug === examTypeSlug);
  if (!examType) return [];
  return paperTypes.filter((p) => p.examTypeId === examType.id);
}

export function getSubjectsByCategory(examTypeSlug: string, categorySlug: string): Subject[] {
  const examType = examTypes.find((e) => e.slug === examTypeSlug);
  const category = subjectCategories.find(
    (c) => c.examTypeId === examType?.id && c.slug === categorySlug
  );
  if (!category) return [];
  return subjects.filter((s) => s.categoryId === category.id);
}
