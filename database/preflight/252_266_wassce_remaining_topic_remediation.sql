state AS (
 SELECT *,CASE
  WHEN target_present=1500 AND target_subjects=1500 AND target_nulls=1500 AND target_mapped=0 AND ledger_rows=0 AND topics_present=0 AND topics_exact=0 AND topic_collisions=0 AND excluded_present IN (0,69) AND excluded_non_null=0 AND excluded_ledgers=0 AND elective_math_ledgers=0 AND cross_subject_links=0 AND unexpected_live_nulls=0 THEN 'pristine_pre'
  WHEN target_present=1500 AND target_subjects=1500 AND target_nulls=0 AND target_mapped=1500 AND ledger_rows=1500 AND ledger_exact=1500 AND topics_present=20 AND topics_exact=20 AND topic_collisions=0 AND complete_batches=15 AND excluded_present IN (0,69) AND excluded_non_null=0 AND excluded_ledgers=0 AND elective_math_ledgers=0 AND cross_subject_links=0 AND unexpected_live_nulls=0 THEN 'applied_post'
  WHEN target_present=1500 AND target_subjects=1500 AND target_nulls=1500 AND target_mapped=0 AND ledger_rows=1500 AND ledger_exact=1500 AND topics_present=0 AND topics_exact=0 AND topic_collisions=0 AND complete_batches=15 AND excluded_present IN (0,69) AND excluded_non_null=0 AND excluded_ledgers=0 AND elective_math_ledgers=0 AND cross_subject_links=0 AND unexpected_live_nulls=0 THEN 'rolled_back'
  ELSE 'invalid' END release_state
 FROM stats
)
SELECT 'release_state' check_name,release_state actual,'pristine_pre|applied_post|rolled_back' expected FROM state
UNION ALL SELECT 'release_state_valid',CASE WHEN release_state='invalid' THEN 0 ELSE 1 END,1 FROM state
UNION ALL SELECT 'target_rows_present',target_present,1500 FROM state
UNION ALL SELECT 'target_subjects_exact',target_subjects,1500 FROM state
UNION ALL SELECT 'target_nulls',target_nulls,CASE WHEN release_state='applied_post' THEN 0 ELSE 1500 END FROM state
UNION ALL SELECT 'target_exact_mappings',target_mapped,CASE WHEN release_state='applied_post' THEN 1500 ELSE 0 END FROM state
UNION ALL SELECT 'release_ledger_rows',ledger_rows,CASE WHEN release_state='pristine_pre' THEN 0 ELSE 1500 END FROM state
UNION ALL SELECT 'release_ledger_exact',ledger_exact,CASE WHEN release_state='pristine_pre' THEN 0 ELSE 1500 END FROM state
UNION ALL SELECT 'proposed_topic_ids',topics_present,CASE WHEN release_state='applied_post' THEN 20 ELSE 0 END FROM state
UNION ALL SELECT 'proposed_topic_contract',topics_exact,CASE WHEN release_state='applied_post' THEN 20 ELSE 0 END FROM state
UNION ALL SELECT 'proposed_topic_collisions',topic_collisions,0 FROM state
UNION ALL SELECT 'repo_only_count_valid',CASE WHEN excluded_present IN (0,69) THEN 1 ELSE 0 END,1 FROM state
UNION ALL SELECT 'repo_only_non_null',excluded_non_null,0 FROM state
UNION ALL SELECT 'repo_only_release_ledgers',excluded_ledgers,0 FROM state
UNION ALL SELECT 'elective_math_release_ledgers',elective_math_ledgers,0 FROM state
UNION ALL SELECT 'unexpected_live_nulls',unexpected_live_nulls,0 FROM state
UNION ALL SELECT 'global_cross_subject_links',cross_subject_links,0 FROM state;
